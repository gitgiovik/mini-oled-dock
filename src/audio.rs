struct VolumeWatch {
    ui_hwnd: isize,
}

impl IAudioEndpointVolumeCallback_Impl for VolumeWatch_Impl {
    fn OnNotify(&self, pnotify: *mut AUDIO_VOLUME_NOTIFICATION_DATA) -> WinResult<()> {
        // SAFETY: WASAPI passes a pointer valid for the duration of the callback (or null,
        // handled by `as_ref`); only scalar fields are read.
        if let Some(d) = unsafe { pnotify.as_ref() } {
            let level = (d.fMasterVolume.clamp(0.0, 1.0) * 100.0).round() as u8;
            post_volume(self.ui_hwnd, VolumeState { level, muted: d.bMuted.as_bool(), available: true });
        }
        Ok(())
    }
}

/// `IMMNotificationClient`: tells the shell thread that the default device changed
/// (or that a device appeared/disappeared/changed state); the shell thread will do the reopening.
#[implement(IMMNotificationClient)]
struct DeviceWatch;

fn wake_shell() {
    let tid = crate::shell_thread::thread_id();
    if tid != 0 {
        // SAFETY: PostThreadMessageW is thread-safe; it only fails if the thread no longer exists.
        let _ = unsafe { PostThreadMessageW(tid, WM_SHELL_AUDIO_DEVICE_CHANGED, WPARAM(0), LPARAM(0)) };
    }
}

impl IMMNotificationClient_Impl for DeviceWatch_Impl {
    fn OnDeviceStateChanged(&self, _id: &PCWSTR, _state: DEVICE_STATE) -> WinResult<()> {
        wake_shell();
        Ok(())
    }
    fn OnDeviceAdded(&self, _id: &PCWSTR) -> WinResult<()> {
        wake_shell();
        Ok(())
    }
    fn OnDeviceRemoved(&self, _id: &PCWSTR) -> WinResult<()> {
        wake_shell();
        Ok(())
    }
    fn OnDefaultDeviceChanged(&self, flow: EDataFlow, role: ERole, _id: &PCWSTR) -> WinResult<()> {
        if flow == eRender && role == eConsole {
            wake_shell();
        }
        Ok(())
    }
    fn OnPropertyValueChanged(&self, _id: &PCWSTR, _key: &PROPERTYKEY) -> WinResult<()> {
        Ok(())
    }
}

